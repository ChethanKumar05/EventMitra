-- Generate a filled copy: npm run admin:bootstrap:sql
-- Apply migrations through 010 first. Execute the generated .local/admin-bootstrap.sql
-- in pgAdmin Query Tool. No API login is required; no plaintext password is stored.
DO $eventmitra_bootstrap$
DECLARE
  bootstrap_email TEXT := E'__ADMIN_EMAIL__';
  bootstrap_name TEXT := E'__ADMIN_NAME__';
  bootstrap_username TEXT := E'__ADMIN_USERNAME__';
  bootstrap_hash TEXT := E'__PASSWORD_HASH__';
  bootstrap_role_id VARCHAR(26) := E'__ROLE_ID__';
  bootstrap_admin_id VARCHAR(26) := E'__ADMIN_ID__';
  existing_role_id VARCHAR(26);
  generated_admin_code TEXT;
  generated_role_code TEXT;
BEGIN
  PERFORM pg_advisory_xact_lock(71003601);
  IF to_regclass('public.migrations_history') IS NULL THEN
    RAISE EXCEPTION 'Run npm run migrate before this bootstrap script';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.migrations_history WHERE migration_name='010_admin_identity_validation_migration') THEN
    RAISE EXCEPTION 'Migrations through 010 must be applied. Run npm run migrate';
  END IF;
  bootstrap_email:=lower(btrim(bootstrap_email));
  bootstrap_name:=btrim(bootstrap_name);
  IF length(bootstrap_email)>255 OR bootstrap_email !~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$' THEN
    RAISE EXCEPTION 'Supply your own valid email';
  END IF;
  IF bootstrap_username !~ '^[a-zA-Z0-9][a-zA-Z0-9_.-]{2,49}$' THEN
    RAISE EXCEPTION 'Username must have 3-50 letters/digits/dots/underscores/hyphens and no whitespace';
  END IF;
  bootstrap_username:=lower(bootstrap_username);
  IF bootstrap_name='' OR length(bootstrap_name)>150 THEN
    RAISE EXCEPTION 'Supply your own name (1-150 characters)';
  END IF;
  IF bootstrap_hash !~ '^scrypt-v1[$][a-f0-9]{32}[$][a-f0-9]{128}$' THEN
    RAISE EXCEPTION 'Supply a hash generated by npm run admin:bootstrap:sql; plaintext and bcrypt are not accepted';
  END IF;
  IF bootstrap_role_id !~ '^[0-7][0-9A-HJKMNP-TV-Z]{25}$' OR bootstrap_admin_id !~ '^[0-7][0-9A-HJKMNP-TV-Z]{25}$' THEN
    RAISE EXCEPTION 'Supply generated ULIDs, or use npm run admin:bootstrap:sql';
  END IF;
  IF EXISTS (SELECT 1 FROM public.admin WHERE is_super_admin) THEN
    RAISE EXCEPTION 'A super admin already exists. This script only creates the first one; it does not reset or overwrite accounts';
  END IF;
  IF EXISTS (SELECT 1 FROM public.admin WHERE lower(admin_email)=bootstrap_email OR lower(admin_username)=bootstrap_username) THEN
    RAISE EXCEPTION 'Email or username already exists; no existing account has been changed';
  END IF;
  SELECT role_id,role_code INTO existing_role_id,generated_role_code FROM public.roles
    WHERE lower(regexp_replace(btrim(role_type),'[[:space:]]+',' ','g'))='super admin';
  IF existing_role_id IS NULL THEN
    INSERT INTO public.roles(role_id,role_type) VALUES (bootstrap_role_id,'Super admin') RETURNING role_code INTO generated_role_code;
  ELSE
    bootstrap_role_id:=existing_role_id;
  END IF;
  INSERT INTO public.admin(admin_id,admin_name,admin_username,admin_email,role_id,password_hash,status,is_super_admin)
    VALUES (bootstrap_admin_id,bootstrap_name,bootstrap_username,bootstrap_email,bootstrap_role_id,bootstrap_hash,'active',true)
    RETURNING admin_code INTO generated_admin_code;
  -- The super-admin flag grants all current/future module actions without grant rows.
  RAISE NOTICE 'First super admin created. Admin code: %, role code: %',generated_admin_code,generated_role_code;
END;
$eventmitra_bootstrap$;
SELECT a.admin_id,a.admin_code,a.admin_name,a.admin_username,a.admin_email,a.status,a.is_super_admin,r.role_id,r.role_code,r.role_type
FROM public.admin a JOIN public.roles r USING(role_id) WHERE a.is_super_admin AND a.status='active';
